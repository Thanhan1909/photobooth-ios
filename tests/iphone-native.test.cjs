'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../ios-app');
const html=fs.readFileSync(path.join(root,'www','index.html'),'utf8');
const bridge=fs.readFileSync(path.join(root,'www','native-photos.js'),'utf8');
const config=JSON.parse(fs.readFileSync(path.join(root,'capacitor.config.json'),'utf8'));
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
assert.equal(config.webDir,'www');
assert.equal(config.appName,'BloomBooth');
assert.ok(html.includes('./native-photos.js'));
assert.ok(html.includes('./selection-engine.js'));
assert.ok(!html.includes('src="/mobile/'));
assert.ok(!html.includes('pwa-install-note'));
assert.ok(!html.includes('<script src="./pwa.js"'));
assert.ok(bridge.includes('BloomNativePhotos'));
assert.ok(bridge.includes('savePhoto'));
assert.ok(bridge.includes('data:image/jpeg;base64,'));
assert.ok(pkg.dependencies['@capacitor-community/media']);
assert.ok(!fs.existsSync(path.join(root,'www','sw.js')));
assert.ok(!fs.existsSync(path.join(root,'www','pwa.js')));
console.log('PASS: packaged iOS-native app includes Photos bridge, capture selection, and offline web assets');
