'use strict';
const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs'),path=require('node:path');
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../mobile/selection-engine.js'),'utf8'),sandbox);
const e=sandbox.window.BloomSelection;
assert.equal(e.config(1).captureCount,1);
assert.equal(e.config(3,5).needsSelection,true);
assert.equal(e.config(5).needsSelection,false);
assert.throws(()=>e.config(3,2));
const shots=['A','B','C','D','E'];
let picked=[];
picked=e.choose(picked,4,3,5);picked=e.choose(picked,1,3,5);picked=e.choose(picked,3,3,5);
assert.equal(JSON.stringify(picked),'[4,1,3]');
picked=e.choose(picked,0,3,5);
assert.equal(JSON.stringify(picked),'[4,1,3]','Do not select more than 3');
assert.equal(JSON.stringify(e.arrange(shots,picked,3)),'["E","B","D"]');
picked=e.choose(picked,1,3,5);
assert.equal(JSON.stringify(picked),'[4,3]');
assert.throws(()=>e.arrange(shots,picked,3));
assert.throws(()=>e.arrange(shots,[1,1,2],3));
console.log('PASS: capture 5, select 3, preserve selection order, reject incomplete/duplicate selection');
